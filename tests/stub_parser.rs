use global_asm::ntdll::parse_syscall_number;

fn nt_open_process() -> Vec<u8> {
    vec![
        0x4C, 0x8B, 0xD1, // mov r10, rcx
        0xB8, 0x26, 0x00, 0x00, 0x00, // mov eax, 0x26
        0xF6, 0x04, 0x25, 0x08, 0x03, 0xFE, 0x7F, 0x01, // test byte ptr [7FFE0308h],1
        0x75, 0x03, // jne +3
        0x0F, 0x05, // syscall
        0xC3, // ret
        0xCD, 0x2E, 0xC3, // int 2Eh ; ret
    ]
}

fn minimal() -> Vec<u8> {
    vec![
        0x4C, 0x8B, 0xD1, 0xB8, 0x32, 0x00, 0x00, 0x00, 0x0F, 0x05, 0xC3,
    ]
}

fn mov_r10d() -> Vec<u8> {
    vec![
        0x44, 0x8B, 0xD1, 0xB8, 0x18, 0x00, 0x00, 0x00, 0x0F, 0x05, 0xC3,
    ]
}

fn padded() -> Vec<u8> {
    let mut v = vec![0xCC, 0xCC, 0xCC, 0xCC, 0xCC];
    v.extend_from_slice(&[0x4C, 0x8B, 0xD1, 0xB8, 0x55, 0x00, 0x00, 0x00]);
    v.extend_from_slice(&[0xF6, 0x04, 0x25, 0x08, 0x03, 0xFE, 0x7F, 0x01, 0x75, 0x03]);
    v.extend_from_slice(&[0x0F, 0x05, 0xC3]);
    v
}

fn high_ssn() -> Vec<u8> {
    vec![
        0x4C, 0x8B, 0xD1, 0xB8, 0x9B, 0x01, 0x00, 0x00, 0x0F, 0x05, 0xC3,
    ]
}

#[test]
fn classic_stub() {
    assert_eq!(parse_syscall_number(&nt_open_process()), Some(0x26));
}

#[test]
fn minimal_stub() {
    assert_eq!(parse_syscall_number(&minimal()), Some(0x32));
}

#[test]
fn mov_r10d_stub() {
    assert_eq!(parse_syscall_number(&mov_r10d()), Some(0x18));
}

#[test]
fn padded_stub() {
    assert_eq!(parse_syscall_number(&padded()), Some(0x55));
}

#[test]
fn high_ssn_is_32_bit() {
    assert_eq!(parse_syscall_number(&high_ssn()), Some(0x19B));
}

#[test]
fn hooked_prologue_is_rejected() {
    let hooked = vec![0xE9, 0x12, 0x34, 0x00, 0x00, 0x90, 0x90, 0x90, 0x90];
    assert_eq!(parse_syscall_number(&hooked), None);
}

#[test]
fn truncated_is_rejected() {
    assert_eq!(parse_syscall_number(&[]), None);
    assert_eq!(parse_syscall_number(&[0x4C, 0x8B, 0xD1, 0xB8]), None);
    assert_eq!(parse_syscall_number(&[0x4C, 0x8B]), None);
}

#[test]
fn missing_syscall_or_ret_is_rejected() {
    let no_syscall = vec![0x4C, 0x8B, 0xD1, 0xB8, 0x18, 0x00, 0x00, 0x00, 0x90, 0x90];
    assert_eq!(parse_syscall_number(&no_syscall), None);
    let no_ret = vec![
        0x4C, 0x8B, 0xD1, 0xB8, 0x18, 0x00, 0x00, 0x00, 0x0F, 0x05, 0x90,
    ];
    assert_eq!(parse_syscall_number(&no_ret), None);
}

#[test]
fn wrong_opcode_after_prologue_is_rejected() {
    // mov r10, rcx ; mov ecx, imm32 (0xB9) instead of mov eax
    let wrong = vec![
        0x4C, 0x8B, 0xD1, 0xB9, 0x18, 0x00, 0x00, 0x00, 0x0F, 0x05, 0xC3,
    ];
    assert_eq!(parse_syscall_number(&wrong), None);
}
